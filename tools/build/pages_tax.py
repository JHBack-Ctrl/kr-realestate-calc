def _rows(items):
    cls = ' class="total"'
    return "".join(f'<tr{cls if total else ""}><th scope="row">{k}</th><td>{v}</td></tr>' for k, v, total in items)

def _breakdown(title, items, note):
    return f'''
        <section class="card">
          <h2>{title}</h2>
          <div class="table-wrap"><table class="tbl"><tbody>
            {_rows(items)}
          </tbody></table></div>
          <p class="result-note"><span id="rules-date"></span>. {note}</p>
        </section>'''

