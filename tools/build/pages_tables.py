def table_page(idx, eyebrow, sub, body_sections, related_paths):
    f, name, title, desc, short = TABLES[idx]
    rel = "".join(f'<a class="tool-card" href="{p}"><p class="t">{n}</p><p class="d">{d}</p></a>' for (p, n, _t, _d, _c, d) in [t for t in TOOLS if t[0] in related_paths])
    main = f'''    <section class="hero">
      <p class="eyebrow">{eyebrow}</p>
      <h1>{name}</h1>
      <p class="hero-sub">{sub}</p>
    </section>
{body_sections}{INLINE_AD}
    <section class="card related" aria-labelledby="rel-title">
      <h2 id="rel-title">이 표를 쓰는 계산기</h2>
      <div class="tool-grid">{rel}</div>
    </section>'''
    ld = jsonld({"@context": "https://schema.org", "@type": "Dataset", "name": name, "description": desc, "url": BASE + f, "inLanguage": "ko-KR", "dateModified": TODAY,
                 "creator": {"@type": "Organization", "name": "전국부동산계산기", "url": BASE}, "isAccessibleForFree": True})
    return page(title, desc, f, main, extra_head=ld + breadcrumb_ld(name, f), disclaimer="본 표는 참고용이며 법령 개정에 따라 바뀔 수 있습니다. 금융·세무·법률 자문이 아닙니다.")

def tbl(head, rows, cls="tbl nowrap-head"):
    th = "".join(f'<th scope="col">{h}</th>' for h in head)
    body = ""
    for r in rows:
        cells = "".join((f'<th scope="row">{c}</th>' if i == 0 else f'<td>{c}</td>') for i, c in enumerate(r))
        body += f"<tr>{cells}</tr>"
    return f'<div class="table-wrap"><table class="{cls}"><thead><tr>{th}</tr></thead><tbody>{body}</tbody></table></div>'

def sec(title, inner, note=None):
    n = f'\n      <p class="result-note">{note}</p>' if note else ""
    return f'''
    <section class="card">
      <h2>{title}</h2>
      {inner}{n}
    </section>'''

