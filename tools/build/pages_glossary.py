def term_path(slug): return f"term-{slug}.html"

def term_page(t):
    slug, name, cat, one, paras, rel_paths = t
    path = term_path(slug)
    title = f"{name}이란 — 뜻과 확인 방법 | 부동산 용어 사전"
    desc = f"{name}: {one}. " + re.sub(r"<[^>]+>", "", paras[0])[:110] + "…"
    rel_src = [x for x in TOOLS if x[0] in rel_paths] + [(f, n, "", "", "", d) for (f, n, _t, _d, d) in TABLES + FORMS if f in rel_paths]
    rel = "".join(f'<a class="tool-card" href="{f}"><p class="t">{n}</p><p class="d">{d}</p></a>' for (f, n, _t, _d, _c, d) in rel_src)
    # 같은 분류의 다른 용어
